import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import ts from 'typescript';
const url = s => `data:text/javascript;base64,${Buffer.from(s).toString('base64')}`;
const compile = path => ts.transpileModule(readFileSync(new URL(path, import.meta.url), 'utf8'), { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext } }).outputText;
const pool = url(compile('../src/gacha/pool.ts'));
const { emptyCollection, decodeCollection, addPulls, mergeStack, mergeReward, stackKey } = await import(url(compile('../src/gacha/collection.ts').replace("'./pool'", JSON.stringify(pool))));
const item = { family: 'earth', tier: 'common', depth: 25 };
let saved = addPulls(emptyCollection(), Array(75).fill(item));
assert.equal(saved.total,75);assert.equal(saved.recent.length,50);assert.equal(saved.stacks[0].count,75);
saved = decodeCollection(JSON.stringify(saved));
const merged = mergeStack(saved,stackKey(item));
assert.equal(saved.stacks[0].count,75,'merging does not mutate the prior save');
assert.equal(merged.stacks.reduce((n,t)=>n+t.count,0),73,'consume three, award one');
assert.deepEqual(merged.stacks.find(t=>t.depth===26),{family:'earth',tier:'strong',depth:26,count:1});
assert.equal(merged.total,75);assert.equal(merged.merges,1);
assert.deepEqual(decodeCollection(JSON.stringify(merged)),merged);
assert.equal(mergeStack(merged,'earth:26'),merged,'insufficient copies cannot merge');
assert.equal(mergeStack(merged,'unknown:25'),merged);
assert.equal(mergeReward({family:'earth',tier:'elite',depth:39}),null);
assert.equal(mergeReward({family:'earth',tier:'strong',depth:30}).tier,'elite');
const legacy = decodeCollection(JSON.stringify({total:100,recent:Array(50).fill(item)}));
assert.equal(legacy.stacks[0].count,50);assert.equal(legacy.total,100);assert.ok(legacy.recovered);
for(const raw of ['{', '{}', JSON.stringify({total:1,recent:[{...item,family:'bad'}]}),JSON.stringify({...merged,stacks:[{...item,count:-1}]})]) assert.throws(()=>decodeCollection(raw));
console.log('Verified collection persistence, legacy recovery, merge costs, tier upgrades, depth cap, and corrupt saves.');
